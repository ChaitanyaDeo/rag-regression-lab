"""
Prompted generation over retrieved chunks, via a local Ollama model.

Internal to BuiltinRAGSystem only - not part of the public RAGSystem
contract. A user's own pipeline (see interface.py) generate however it
wants inside its own generate(); it never imports this module.

"""

import re
from typing import List, Tuple
from dataclasses import dataclass
import logging

logger = logging.getLogger(__name__)

from langchain_core.prompts import PromptTemplate
from langchain_ollama import ChatOllama

from ragregress.rag.interface import Chunk, GenerationResult


ABSTENTION_MESSAGE = "The context does not contain enough information to answer this question."

CITATION_REGEX = r"\[source:\s*(p\d+)\]"

# TODO: Fix prompt
PROMPT_TEMPLATE = """ou are a question-answering assistant.
 
Answer the question using ONLY the information in the context below.
Do NOT use outside knowledge or make assumptions.
 
CITATION RULES:
- Every factual claim must have a citation immediately after it.
- A citation must use exactly one passage ID from the context, in this format: [source: p0000042].
- Use only passage IDs that actually appear in the context.
- Cite the passage that directly supports the claim.
- Do not invent, modify, or combine passage IDs.
- If a sentence contains multiple factual claims supported by different passages,
  cite each claim separately.
- If the context does not contain enough information to answer the question,
  say: "{abstention_message}"
 
Keep the answer concise and directly answer the question.
 
Example:
 
Context:
[source: p0000001]
The Eiffel Tower was completed in 1889 for the World's Fair in Paris.
 
Question: When was the Eiffel Tower completed?
 
Answer:
The Eiffel Tower was completed in 1889 [source: p0000001].
 
---
 
Context:
{context}
 
Question: {question}
 
Answer:
"""
GENERATION_PROMPT = PromptTemplate.from_template(PROMPT_TEMPLATE)

@dataclass
class GeneratorConfig:
    """Per-run configuration for BuiltinRAGSystem's generation step

    """
    model_name: str = "qwen2.5:3b-instruct"
    temperature: float = 0
    seed: int = 42  #  fixed seed for reproducible generation


def parse_citations(text: str)-> Tuple[str, List[str]]:
    """
    Extract citation from text generated by generator
    """
    
    match_cites = re.findall(CITATION_REGEX, text)
    citations = list(dict.fromkeys(match_cites))

    no_brackets = re.sub(CITATION_REGEX, "", text)
    answer = re.sub(r"\s+", " ", no_brackets).strip()

    return answer, citations

def build_context(contexts: List[Chunk]) -> str:
    """Format retrieved chunks into the prompt's context block.

    """
    return "\n\n".join(
        f"[source: {chunk.source_passage_id}]\n{chunk.text}" for chunk in contexts
    )



def run_generation(question: str, contexts: List[Chunk], config: GeneratorConfig):

    context = build_context(contexts)

    llm = ChatOllama(model=config.model_name, temperature=config.temperature, seed=config.seed)

    chain = GENERATION_PROMPT | llm 

    response = chain.invoke({"context": context, "question": question, "abstention_message": ABSTENTION_MESSAGE})

    return response.content

def generate_with_citations(question: str, contexts: List[Chunk], config: GeneratorConfig) -> GenerationResult:

    """Full generation step: prompt -> LLM -> parsed GenerationResult.

    Logs a warning if the model produced a real (non-abstention) answer with
    zero parseable citations
    """

    raw_output = run_generation(question, contexts, config)
    answer, citations = parse_citations(raw_output)

    is_abstention = answer.strip() == ABSTENTION_MESSAGE

    if not citations and not is_abstention:
        logger.warning(
            "generate_with_citations: no citations found in a non-abstention "
            "answer for question=%r", question
        )


    return GenerationResult(raw_output=raw_output, answer=answer, citations=citations)





