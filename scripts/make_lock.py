"""
scripts/make_lock.py   Day 13 B4: write requirements.lock from what is installed in the image.

    docker compose run --rm --entrypoint python ragregress scripts/make_lock.py

requirements.txt pins the direct dependencies only; this file pins every installed package (direct and
transitive), so a build can be reproduced exactly. It describes the Linux CPU image. Differences from a
raw `pip freeze`:
  - the ragregress package itself is left out;
  - torch's local version tag is dropped ("2.11.0+cpu" -> "2.11.0"), because the tag only exists on the
    CPU index. Install torch from the index you want, as the comments in requirements.txt describe.

Writes ./requirements.lock (the working directory: /work in the container, so the file lands in the repo
root on your disk). Prints nothing but the path and the number of packages.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path
from typing import List

LOCK_NAME = "requirements.lock"
HEADER = (
    "# requirements.lock: every package installed in the Docker image, pinned (Linux, Python 3.11, CPU torch).\n"
    "# Generated by scripts/make_lock.py. Do not edit; regenerate after changing requirements.txt.\n"
    "# Direct dependencies and their reasons live in requirements.txt; this file is for exact reproduction.\n"
)
_LOCAL_VERSION = re.compile(r"^([A-Za-z0-9_.\-]+==[^+\s]+)\+\S+$")


def lock_lines(freeze_output: str) -> List[str]:
    """`pip freeze` text -> sorted pinned lines, without ragregress itself and without local version tags."""
    lines = []
    for raw in freeze_output.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or line.startswith("-e "):
            continue
        name = re.split(r"[=@ ]", line, maxsplit=1)[0]
        if normalise(name) == "ragregress":
            continue
        match = _LOCAL_VERSION.match(line)
        lines.append(match.group(1) if match else line)
    return sorted(lines, key=lambda l: normalise(re.split(r"[=@ ]", l, maxsplit=1)[0]))


def normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def lock_text(freeze_output: str) -> str:
    return HEADER + "\n".join(lock_lines(freeze_output)) + "\n"


def main() -> int:
    freeze = subprocess.run([sys.executable, "-m", "pip", "freeze", "--exclude-editable"],
                            capture_output=True, text=True, check=True).stdout
    text = lock_text(freeze)
    path = Path(LOCK_NAME)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.resolve()} ({len(lock_lines(freeze))} packages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())